import dotenv from 'dotenv';
dotenv.config({ override: true });
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { AgentOrchestrator } from '../src/agent/orchestrator.mjs';
import { OpenAICompatibleProvider } from '../src/agent/llm/provider.mjs';

const MCP_URL = process.env.MCP_SERVER_URL || 'http://127.0.0.1:3001/mcp';

async function runRealLLMAgentExecution() {
  console.log('========================================================================');
  console.log('ALEXA+ MILESTONE 3.1: REAL LLM-DRIVEN AGENT VERIFICATION HARNESS');
  console.log('========================================================================');

  const rawKey = process.env.OPENAI_API_KEY || '';
  const isPlaceholder = !rawKey || rawKey === 'your_key_here' || rawKey.includes('placeholder');
  const baseURL = process.env.OPENAI_BASE_URL || 'https://api.openai.com/v1';
  const model = process.env.LLM_MODEL || 'gpt-4o';

  console.log('[Environment Audit]');
  console.log(`  - Provider Name: OpenAICompatibleProvider`);
  console.log(`  - Configured Model: ${model}`);
  console.log(`  - Target Endpoint: ${baseURL}/chat/completions`);
  console.log(`  - API Key Configured: ${Boolean(rawKey)} (Valid/Active: ${!isPlaceholder})`);

  if (isPlaceholder) {
    console.warn('\n[REAL LLM EXECUTION BLOCKED]');
    console.warn('  Reason: OPENAI_API_KEY is currently a placeholder ("your_key_here").');
    console.warn('  A valid, funded OpenAI API key or a compatible live local endpoint is required for live external inference.');
    console.warn('  Halting real-provider invocation to prevent unauthorized network failures.');
    return {
      status: 'BLOCKED',
      reason: 'No valid provider credential configured'
    };
  }

  console.log(`\n[MCP Client] Connecting to: ${MCP_URL}`);
  const transport = new StreamableHTTPClientTransport(new URL(MCP_URL));
  const mcpClient = new Client(
    { name: 'alexa-plus-real-llm-client', version: '1.0.0' },
    { capabilities: { roots: {} } }
  );

  try {
    await mcpClient.connect(transport);
    console.log(`[MCP Transport Connected] MCP Session ID: ${transport.sessionId}\n`);

    const realProvider = new OpenAICompatibleProvider({
      apiKey: rawKey,
      baseURL,
      model
    });

    const orchestrator = new AgentOrchestrator({
      mcpClient,
      llmProvider: realProvider,
      maxIterations: 6,
      timeoutMs: 45000
    });

    // MISSION 1: Primary Real-LLM Mission
    console.log('========================================================================');
    console.log('MISSION 1: "Prepare me for my Product Roadmap Discussion tomorrow."');
    console.log('========================================================================');

    const mission1 = await orchestrator.executeMission(
      'Prepare me for my Product Roadmap Discussion tomorrow.'
    );

    console.log('\n[MISSION 1 RESULT]:');
    console.log(`  - Status: ${mission1.status}`);
    console.log(`  - Tool Calls Executed: ${mission1.toolCallsExecutedCount}`);
    console.log(`  - Sequence: ${mission1.toolTraces.map(t => t.toolName).join(' -> ')}`);
    console.log('\n[MISSION 1 FINAL ANSWER GENERATED BY REAL MODEL]:');
    console.log(mission1.finalAnswer);

    // MISSION 2: Secondary Real-LLM Mission
    console.log('\n========================================================================');
    console.log('MISSION 2: "Search my knowledge base for documents about competitor analysis."');
    console.log('========================================================================');

    const mission2 = await orchestrator.executeMission(
      'Search my knowledge base for documents about competitor analysis.'
    );

    console.log('\n[MISSION 2 RESULT]:');
    console.log(`  - Status: ${mission2.status}`);
    console.log(`  - Tool Calls Executed: ${mission2.toolCallsExecutedCount}`);
    console.log(`  - Sequence: ${mission2.toolTraces.map(t => t.toolName).join(' -> ')}`);
    console.log('\n[MISSION 2 FINAL ANSWER GENERATED BY REAL MODEL]:');
    console.log(mission2.finalAnswer);

    await transport.close();
    return {
      status: 'SUCCESS',
      mission1,
      mission2
    };
  } catch (error) {
    console.error('\n[REAL LLM EXECUTION ERROR]:', error.message);
    try {
      await transport.close();
    } catch {}
    throw error;
  }
}

runRealLLMAgentExecution();
